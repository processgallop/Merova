// Embeds drizzle-kit SQL migrations into src/db/migrations.generated.ts
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const files = readdirSync("drizzle").filter((f) => f.endsWith(".sql")).sort();
const list = files.map((f) => ({ name: f.replace(/\.sql$/, ""), sql: readFileSync(`drizzle/${f}`, "utf8") }));
writeFileSync(
  "src/db/migrations.generated.ts",
  `// Generated by scripts/embed-migrations.mjs — do not edit.\nexport const migrations: { name: string; sql: string }[] = ${JSON.stringify(list, null, 2)};\n`,
);
console.log(`Embedded ${list.length} migration(s).`);
