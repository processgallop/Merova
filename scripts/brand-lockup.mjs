// Builds a horizontal lockup from the official master artwork: the exact mark
// path and the exact wordmark glyph outlines, repositioned side by side (no
// redrawing, no distortion — uniform scaling only). Requires brand approval.
import { readFileSync, writeFileSync } from "node:fs";

const s = readFileSync("public/assets/brand/merova-logo-primary.svg", "utf8");
const [defsPart, body] = s.split("</defs>");
const defs = defsPart.slice(defsPart.indexOf("<defs>"));
const markD = body.match(/<path[^>]*d="([^"]+)"/)[1];
const uses = [...body.matchAll(/<use xlink:href="#(glyph-[^"]+)" x="([\d.]+)" y="([\d.]+)"\/>/g)];
const MARK = { x0: 153.675781, y0: 48.632812, w: 847.996094 - 153.675781, h: 351.34375 - 48.632812 };
const WM = { x0: 653.6338, base: 119.8066, cap: 50.1 };
const k = (MARK.h * 0.5) / WM.cap; // wordmark cap height = half the mark height
const gap = 70;
const wmX = MARK.w + gap;
const wmY = MARK.h * 0.75; // baseline
const width = Math.ceil(wmX + (925 - WM.x0) * k);

const build = (markFill, textFill) => `<?xml version="1.0" encoding="UTF-8"?>
<svg role="img" aria-label="Merova" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 ${width} ${Math.ceil(MARK.h)}" width="${width}" height="${Math.ceil(MARK.h)}">
${defs}</defs>
<path fill="${markFill}" transform="translate(${-MARK.x0} ${-MARK.y0})" d="${markD}"/>
<g fill="${textFill}" transform="translate(${wmX} ${wmY}) scale(${k}) translate(${-WM.x0} ${-WM.base})">
${uses.map((u) => `<use xlink:href="#${u[1]}" x="${u[2]}" y="${u[3]}"/>`).join("\n")}
</g>
</svg>
`;

writeFileSync("public/assets/brand/merova-lockup-horizontal.svg", build("#d52b1e", "#454040"));
writeFileSync("public/assets/brand/merova-lockup-horizontal-light.svg", build("#d52b1e", "#fffaf3"));
writeFileSync("public/assets/brand/merova-lockup-horizontal-reverse.svg", build("#fffaf3", "#fffaf3"));
// Emblem path only, normalised to its own bounding box, for motion/watermark use.
writeFileSync(
  "src/components/brand/emblem-path.ts",
  `// Generated by scripts/brand-lockup.mjs from the official master artwork. Do not edit.\nexport const EMBLEM_VIEWBOX = "0 0 ${MARK.w.toFixed(2)} ${MARK.h.toFixed(2)}";\nexport const EMBLEM_TRANSFORM = "translate(${-MARK.x0} ${-MARK.y0})";\nexport const EMBLEM_PATH = ${JSON.stringify(markD)};\n`,
);
console.log("lockup ratio", (width / MARK.h).toFixed(4), "width", width, "height", Math.ceil(MARK.h));
